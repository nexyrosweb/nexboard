/** @param {string} s @param {[string, string][]} pairs */
function applyReplacements(s, pairs) {
  let out = s;
  for (const [from, to] of pairs) {
    if (out === from) {
      out = to;
      continue;
    }
    const safe = from.length >= 10 || /[\s«({]/.test(from);
    if (!safe) continue;
    if (out.includes(from)) out = out.split(from).join(to);
  }
  return out;
}

